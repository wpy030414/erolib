-- Tag translation layer (separate from the main schema to avoid polluting it).
--
-- Books arrive from four sources with tags in many languages/forms (Chinese,
-- Japanese kanji/hiragana/katakana, English, romaji). This file provides a
-- self-contained lookup so QUERIES can render every tag in the CURRENT app
-- locale without touching stored metadata. The `tags`/`book_tags` tables are
-- never modified; translation happens at read time via a JOIN.
--
-- Layout:
--   settings          — tiny KV store (holds `locale`, written by set_locale).
--   tag_translations  — one row per tag CONCEPT, five flat columns holding the
--                       concept's spelling in each form. The five columns are
--                       PURE (only that form), used both to RECOGNIZE a raw tag
--                       and to pick the display label for a locale.
--   v_tag_form        — UNION view mapping every recognizable form → its
--                       concept row, so a single JOIN resolves any raw form.
--
-- Display-label rule (applied in SQL, see services/search.rs `display_expr`):
--   zh → zh;  en → en;  ja → COALESCE(ja_kata, ja_hira, romaji)  (kanji block
--   preferred — the kata column carries the kanji/katakana form);  a missing
--   cell falls back through COALESCE, and a tag with NO mapping falls back to
--   its raw stored name. Everything is idempotent (CREATE IF NOT EXISTS +
--   INSERT OR IGNORE keyed on fixed ids), so it re-runs harmlessly on launch.

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS tag_translations (
    id INTEGER PRIMARY KEY,
    zh TEXT,
    en TEXT,
    ja_hira TEXT,   -- hiragana form
    ja_kata TEXT,   -- katakana / kanji block (preferred for Japanese display)
    romaji TEXT
);

-- Any recognizable form → concept id. Matched case-insensitively at JOIN time
-- (tags.name COLLATE NOCASE = v_tag_form.form). Small table; a full scan per
-- lookup is fine and a view needs no index.
CREATE VIEW IF NOT EXISTS v_tag_form AS
    SELECT id, zh      AS form FROM tag_translations WHERE zh      IS NOT NULL AND zh      <> ''
    UNION
    SELECT id, en                FROM tag_translations WHERE en      IS NOT NULL AND en      <> ''
    UNION
    SELECT id, ja_hira           FROM tag_translations WHERE ja_hira IS NOT NULL AND ja_hira <> ''
    UNION
    SELECT id, ja_kata           FROM tag_translations WHERE ja_kata IS NOT NULL AND ja_kata <> ''
    UNION
    SELECT id, romaji            FROM tag_translations WHERE romaji  IS NOT NULL AND romaji  <> '';

-- Materialized form → concept map for the FAST exact-match path (queries JOIN
-- this indexed table instead of rescanning the UNION view). Filled at startup
-- and on new-tag upsert from `v_tag_form` (see db/mod.rs / services/locale.rs).
CREATE TABLE IF NOT EXISTS tag_form_map (
    form TEXT PRIMARY KEY COLLATE NOCASE,
    tid INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tfm_tid ON tag_form_map(tid);

-- Fully-resolved raw tag name → concept id, covering BOTH exact and fuzzy
-- matches. This is what the read queries JOIN (one indexed lookup, never a
-- per-row fuzzy scan). Exact matches are preferred; a name only gets a fuzzy
-- entry when it has no exact hit (best concept with a clear margin). Filled at
-- startup and on new-tag upsert. `name` is NOCASE so lookups are
-- case-insensitive like the exact path.
CREATE TABLE IF NOT EXISTS tag_resolved (
    name TEXT PRIMARY KEY COLLATE NOCASE,
    tid INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tr_tid ON tag_resolved(tid);

